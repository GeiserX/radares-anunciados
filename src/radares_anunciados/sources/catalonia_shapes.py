def _parse(ring: str) -> list[tuple[float, float]]:
    return [(float(lat), float(lon)) for lat, lon in (p.split(",") for p in ring.split())]


_SHAPES = {code: [_parse(r) for r in rings] for code, rings in RINGS.items()}


def _inside(lat: float, lon: float, ring: list[tuple[float, float]]) -> bool:
    found = False
    for (lat1, lon1), (lat2, lon2) in zip(ring, ring[1:] + ring[:1], strict=True):
        if (lat1 > lat) != (lat2 > lat):
            if lon < lon1 + (lat - lat1) * (lon2 - lon1) / (lat2 - lat1):
                found = not found
    return found


def _edge_m(lat: float, lon: float, ring: list[tuple[float, float]]) -> float:
    """Metres from the point to the nearest edge of ``ring`` (flat, fine at this size)."""
    kx, ky = 111_320 * math.cos(math.radians(lat)), 110_540
    best = math.inf
    for (lat1, lon1), (lat2, lon2) in zip(ring, ring[1:] + ring[:1], strict=True):
        ax, ay = (lon1 - lon) * kx, (lat1 - lat) * ky
        dx, dy = (lon2 - lon1) * kx, (lat2 - lat1) * ky
        length = dx * dx + dy * dy
        t = 0.0 if length == 0 else max(0.0, min(1.0, -(ax * dx + ay * dy) / length))
        best = min(best, math.hypot(ax + t * dx, ay + t * dy))
    return best


def inside(lat: float, lon: float) -> bool:
    """True for a point inside one of the four outlines, with no margin: it tells
    Catalonia from Andorra or France just across the border, where ``province``
    and its coast margin would still answer."""
    return any(sum(_inside(lat, lon, r) for r in rings) % 2 for rings in _SHAPES.values())


def province(lat: float, lon: float) -> str | None:
    """INE code ("08", "17", "25", "43") of the province the point is in; the
    nearest one within ``COAST_M``; None for a point outside Catalonia."""
    for code, rings in _SHAPES.items():
        if sum(_inside(lat, lon, r) for r in rings) % 2:
            return code
    distance, code = min((_edge_m(lat, lon, r), c) for c, rings in _SHAPES.items() for r in rings)
    return code if distance <= COAST_M else None
